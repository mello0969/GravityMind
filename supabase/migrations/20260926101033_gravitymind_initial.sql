-- Server-only backend: custom HttpOnly sessions are preserved during the D1 migration.
-- No browser role can read password hashes, sessions, notes or subscription entitlements.
create table public.users (
  id uuid primary key,
  nome text not null check (char_length(nome) between 2 and 80),
  email text not null unique check (char_length(email) <= 254 and email = lower(email)),
  senha_hash text not null,
  senha_salt text not null,
  criado_em timestamptz not null default now()
);
create table public.sessoes (
  token text primary key check (token ~ '^[a-f0-9]{64}$'),
  user_id uuid not null references public.users(id) on delete cascade,
  expira_em timestamptz not null,
  criado_em timestamptz not null default now()
);
create index on public.sessoes(user_id, criado_em desc);
create index on public.sessoes(expira_em);
create table public.respostas_questoes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  questao_id text not null,
  letra_escolhida text not null check (letra_escolhida in ('A','B','C','D','CALC')),
  correta integer not null check (correta in (0,1)),
  tempo_segundos integer not null check (tempo_segundos between 1 and 7200),
  respondido_em timestamptz not null,
  confianca text check (confianca in ('baixa','media','alta')),
  corrigida integer not null default 0 check (corrigida in (0,1)),
  unique(user_id, questao_id, respondido_em)
);
create index on public.respostas_questoes(user_id, respondido_em desc);
create table public.respostas_calculo (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  questao_id text not null,
  valor_digitado double precision not null check (valor_digitado between -1000000000 and 1000000000),
  correta integer not null check (correta in (0,1)),
  diagnostico text check (char_length(diagnostico) <= 1000),
  tempo_segundos integer not null check (tempo_segundos between 1 and 7200),
  respondido_em timestamptz not null,
  unique(user_id, questao_id, respondido_em)
);
create index on public.respostas_calculo(user_id, respondido_em desc);
create table public.notas (
  id text primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  titulo text not null,
  conteudo text not null default '',
  assunto text not null check (assunto in ('geral','lei-1','lei-2','lei-3')),
  criada_em timestamptz not null,
  atualizada_em timestamptz not null
);
create index on public.notas(user_id, atualizada_em desc);
create table public.notas_historico (
  id bigint generated by default as identity primary key,
  nota_id text not null references public.notas(id) on delete cascade,
  conteudo_anterior text not null,
  salvo_em timestamptz not null
);
create index on public.notas_historico(nota_id);
create table public.progresso_licoes (
  user_id uuid not null references public.users(id) on delete cascade,
  assunto text not null check (assunto in ('lei-1','lei-2','lei-3')),
  marco text not null check (marco in ('texto','narracao','video','resumo','visual','animacao')),
  concluido_em timestamptz not null,
  primary key(user_id, assunto, marco)
);
create table public.dificuldade_adaptativa (
  user_id uuid not null references public.users(id) on delete cascade,
  assunto text not null check (assunto in ('lei-1','lei-2','lei-3')),
  nivel text not null check (nivel in ('facil','medio','dificil')),
  primary key(user_id, assunto)
);
create table public.quiz_resultados (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  assunto text not null check (assunto in ('lei-1','lei-2','lei-3')),
  formato text not null check (char_length(formato) between 1 and 32),
  acertos integer not null check (acertos >= 0 and acertos <= total),
  total integer not null check (total between 1 and 100),
  aprovado integer not null check (aprovado in (0,1)),
  respondido_em timestamptz not null,
  unique(user_id, assunto, formato, respondido_em)
);
create index on public.quiz_resultados(user_id, respondido_em desc);
create table public.rate_limits (
  chave_hash text not null check (chave_hash ~ '^[a-f0-9]{64}$'),
  janela_inicio timestamptz not null,
  requisicoes integer not null check (requisicoes > 0),
  expira_em timestamptz not null,
  primary key(chave_hash, janela_inicio)
);
create index on public.rate_limits(expira_em);
create table public.perfis_estudo (
  user_id uuid primary key references public.users(id) on delete cascade,
  meta_diaria integer not null default 5 check (meta_diaria between 1 and 40),
  ofensiva_dias integer not null default 0 check (ofensiva_dias >= 0),
  ultimo_estudo_em date,
  sequencia_acertos integer not null default 0 check (sequencia_acertos >= 0),
  melhor_sequencia integer not null default 0 check (melhor_sequencia >= 0),
  total_xp integer not null default 0 check (total_xp >= 0),
  atualizado_em timestamptz not null default now()
);
create table public.atividade_estudo (
  user_id uuid not null references public.users(id) on delete cascade,
  data_local date not null,
  respostas integer not null default 0 check (respostas >= 0),
  acertos integer not null default 0 check (acertos >= 0 and acertos <= respostas),
  xp integer not null default 0 check (xp >= 0),
  primary key(user_id, data_local)
);
create table public.eventos_recompensa (
  id uuid not null,
  user_id uuid not null references public.users(id) on delete cascade,
  correta integer not null check (correta in (0,1)),
  corrigida integer not null check (corrigida in (0,1)),
  xp integer not null check (xp between 0 and 100),
  criado_em timestamptz not null default now(),
  primary key(user_id,id)
);
create index on public.eventos_recompensa(user_id, criado_em desc);
create table public.assinaturas (
  user_id uuid primary key references public.users(id) on delete cascade,
  plano text not null default 'free' check (plano in ('free','plus')),
  status text not null default 'inactive' check (status in ('inactive','active','past_due','canceled')),
  provider_customer_id text,
  provider_subscription_id text,
  valida_ate timestamptz,
  atualizado_em timestamptz not null default now()
);
create index on public.assinaturas(provider_subscription_id);

create function public.gm_create_session(p_user_id uuid, p_token text, p_expires timestamptz)
returns void language plpgsql security invoker set search_path = '' as $$
begin
  perform 1 from public.users where id = p_user_id for update;
  delete from public.sessoes where expira_em <= now();
  insert into public.sessoes(token, user_id, expira_em) values (p_token, p_user_id, p_expires);
  delete from public.sessoes where user_id = p_user_id and token not in (
    select token from public.sessoes where user_id = p_user_id
    order by criado_em desc, token desc limit 5
  );
end $$;

create function public.gm_rate_limit(p_key text, p_window timestamptz, p_expires timestamptz)
returns integer language plpgsql security invoker set search_path = '' as $$
declare v_count integer;
begin
  insert into public.rate_limits(chave_hash, janela_inicio, requisicoes, expira_em)
  values(p_key, p_window, 1, p_expires)
  on conflict(chave_hash, janela_inicio) do update set requisicoes = public.rate_limits.requisicoes + 1
  returning requisicoes into v_count;
  if random() < 0.02 then
    delete from public.rate_limits where expira_em < now() - interval '1 day';
  end if;
  return v_count;
end $$;

-- One transaction prevents partial uploads; owner and conflict predicates are never supplied by the browser.
create function public.gm_sync(p_user_id uuid, p_data jsonb)
returns void language plpgsql security invoker set search_path = '' as $$
declare item jsonb;
begin
  for item in select value from jsonb_array_elements(p_data->'notas') loop
    insert into public.notas(id,user_id,titulo,conteudo,assunto,criada_em,atualizada_em)
    values(item->>'id',p_user_id,item->>'titulo',item->>'conteudo',item->>'assunto',
           (item->>'criadaEm')::timestamptz,(item->>'atualizadaEm')::timestamptz)
    on conflict(id) do update set titulo=excluded.titulo,conteudo=excluded.conteudo,
      assunto=excluded.assunto,atualizada_em=excluded.atualizada_em
    where public.notas.user_id=excluded.user_id and excluded.atualizada_em>public.notas.atualizada_em;
  end loop;
  for item in select value from jsonb_array_elements(p_data->'respostasQuestoes') loop
    insert into public.respostas_questoes(user_id,questao_id,letra_escolhida,correta,tempo_segundos,respondido_em,confianca,corrigida)
    values(p_user_id,item->>'questaoId',item->>'letraEscolhida',(item->>'correta')::boolean::integer,
      (item->>'tempoSegundos')::integer,(item->>'respondidoEm')::timestamptz,item->>'confianca',
      coalesce((item->>'corrigida')::boolean::integer,0))
    on conflict(user_id,questao_id,respondido_em) do update set
      confianca=coalesce(excluded.confianca,public.respostas_questoes.confianca),
      corrigida=greatest(public.respostas_questoes.corrigida,excluded.corrigida);
  end loop;
  for item in select value from jsonb_array_elements(p_data->'respostasCalculo') loop
    insert into public.respostas_calculo(user_id,questao_id,valor_digitado,correta,diagnostico,tempo_segundos,respondido_em)
    values(p_user_id,item->>'questaoId',(item->>'valorDigitado')::double precision,
      (item->>'correta')::boolean::integer,item->>'diagnostico',(item->>'tempoSegundos')::integer,
      (item->>'respondidoEm')::timestamptz) on conflict(user_id,questao_id,respondido_em) do nothing;
  end loop;
  for item in select value from jsonb_array_elements(p_data->'progressoLicoes') loop
    insert into public.progresso_licoes values(p_user_id,item->>'assunto',item->>'marco',(item->>'concluidoEm')::timestamptz)
    on conflict(user_id,assunto,marco) do nothing;
  end loop;
  for item in select value from jsonb_array_elements(p_data->'dificuldadeAdaptativa') loop
    insert into public.dificuldade_adaptativa values(p_user_id,item->>'assunto',item->>'nivel')
    on conflict(user_id,assunto) do update set nivel=excluded.nivel;
  end loop;
  for item in select value from jsonb_array_elements(p_data->'quizResultados') loop
    insert into public.quiz_resultados(user_id,assunto,formato,acertos,total,aprovado,respondido_em)
    values(p_user_id,item->>'assunto',item->>'formato',(item->>'acertos')::integer,(item->>'total')::integer,
      (item->>'aprovado')::boolean::integer,(item->>'respondidoEm')::timestamptz)
    on conflict(user_id,assunto,formato,respondido_em) do nothing;
  end loop;
end $$;

create function public.gm_read_profile(p_user_id uuid)
returns table(meta_diaria integer,ofensiva_dias integer,sequencia_acertos integer,
  melhor_sequencia integer,total_xp integer,respostas_hoje integer,acertos_hoje integer,plano text)
language plpgsql security invoker set search_path = '' as $$
begin
  insert into public.perfis_estudo(user_id) values(p_user_id) on conflict(user_id) do nothing;
  return query select p.meta_diaria,p.ofensiva_dias,p.sequencia_acertos,p.melhor_sequencia,p.total_xp,
    coalesce(a.respostas,0),coalesce(a.acertos,0),
    case when s.plano='plus' and s.status='active' and (s.valida_ate is null or s.valida_ate>now())
      then 'plus'::text else 'free'::text end
  from public.perfis_estudo p
  left join public.atividade_estudo a on a.user_id=p.user_id
    and a.data_local=(now() at time zone 'America/Sao_Paulo')::date
  left join public.assinaturas s on s.user_id=p.user_id
  where p.user_id=p_user_id;
end $$;

-- Serialize rewards per student; duplicate event IDs never grant XP twice.
create function public.gm_record_activity(p_user_id uuid,p_event_id uuid,p_correct boolean,p_corrected boolean)
returns void language plpgsql security invoker set search_path = '' as $$
declare
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
  v_xp integer := 4 + case when p_correct then 4 else 0 end + case when p_corrected then 3 else 0 end;
  v_profile public.perfis_estudo;
  v_correct_streak integer;
begin
  insert into public.perfis_estudo(user_id) values(p_user_id) on conflict(user_id) do nothing;
  select * into strict v_profile from public.perfis_estudo where user_id=p_user_id for update;
  insert into public.eventos_recompensa(id,user_id,correta,corrigida,xp)
    values(p_event_id,p_user_id,p_correct::integer,p_corrected::integer,v_xp)
    on conflict(user_id,id) do nothing;
  if not found then return; end if;
  v_correct_streak := case when p_correct then v_profile.sequencia_acertos+1 else 0 end;
  update public.perfis_estudo set
    ofensiva_dias=case when ultimo_estudo_em=v_today then ofensiva_dias
      when ultimo_estudo_em=v_today-1 then ofensiva_dias+1 else 1 end,
    ultimo_estudo_em=v_today, sequencia_acertos=v_correct_streak,
    melhor_sequencia=greatest(melhor_sequencia,v_correct_streak),total_xp=total_xp+v_xp,atualizado_em=now()
    where user_id=p_user_id;
  insert into public.atividade_estudo(user_id,data_local,respostas,acertos,xp)
    values(p_user_id,v_today,1,p_correct::integer,v_xp)
    on conflict(user_id,data_local) do update set
      respostas=public.atividade_estudo.respostas+1,
      acertos=public.atividade_estudo.acertos+excluded.acertos,
      xp=public.atividade_estudo.xp+excluded.xp;
end $$;

do $$
declare t text; f regprocedure;
begin
  foreach t in array array['users','sessoes','respostas_questoes','respostas_calculo','notas','notas_historico',
    'progresso_licoes','dificuldade_adaptativa','quiz_resultados','rate_limits','perfis_estudo',
    'atividade_estudo','eventos_recompensa','assinaturas'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from public, anon, authenticated',t);
    execute format('grant select, insert, update, delete on public.%I to service_role',t);
    execute format('create policy backend_only on public.%I for all to anon, authenticated using (false) with check (false)',t);
  end loop;
  for f in select oid::regprocedure from pg_proc where pronamespace='public'::regnamespace
    and proname in ('gm_create_session','gm_rate_limit','gm_sync','gm_read_profile','gm_record_activity') loop
    execute format('revoke all on function %s from public, anon, authenticated',f);
    execute format('grant execute on function %s to service_role',f);
  end loop;
end $$;
grant usage, select on all sequences in schema public to service_role;
revoke all on all sequences in schema public from anon, authenticated;
